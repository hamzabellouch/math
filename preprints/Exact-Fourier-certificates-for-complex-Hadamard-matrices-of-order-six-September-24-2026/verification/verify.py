def permsign(L):
    pp=[itertools.permutations(s) for s in L]
    for ls in itertools.product(*pp):
        p=list(range(6));invn=0
        for a,b in zip(L,ls):
            for i,z in enumerate(b):
                p[a[i]]=z;invn+=sum(x>z for x in b[:i])
        yield tuple(p), (-1)**invn

